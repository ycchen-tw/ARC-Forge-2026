"""Stage the Kaggle dataset that lays the HiSparse sglang tree over the arc-code runtime archive (no upload).

The Kaggle notebook (work/arc_code/kaggle, config `sglang_tree`) deletes the runtime archive's own sglang source and
extracts this tree in its place, the way the G4 fast path does (g4_runtime_install.sh). The tree is v0.5.20 +
0001-0029 + experimental-hisparse h*, built here from a pristine checkout and asserted against TREE_DIGEST before and
after packing. Staged files:

  sglang-hisparse-<digest12>.tar.zst   python/sglang/** plus the generated _version.py (deterministic tar)
  SOURCE_SHA256-<digest12>             the HiSparse manifest h05 checks at startup (ARC_HISPARSE_QSA_MANIFEST)
  TREE-<digest12>.json                 digest, file count, patch digest, manifest and archive sha256
  dataset-metadata.json                threerabbits/<slug>, private on create

--carry <earlier staging dir> copies the trees an earlier version of the dataset held (every TREE*.json there, with
the archive and manifest it names, each re-verified by sha256) into this version unchanged. A notebook version that
was submitted pins its tree by file name and sha256; carrying the files forward keeps it runnable whichever dataset
version a rerun mounts. The first version (hs55 v1/v2, h18) named its files SOURCE_SHA256 and TREE.json.

--arm <series arm> (arcforge.sglang_series, arc3 = the hs55 v6/v7 tree e93d999a + candidates h40-h43) stages that
arm's tree instead: built from its series file, asserted against TREE_DIGEST.<arm>, manifest <arm>.SOURCE_SHA256,
archive sglang-<arm>-<digest12>.tar.zst (SOURCE_SHA256-<digest12> and TREE-<digest12>.json as for hisparse; the
record carries "arm"). Its serving_responses.py must be the v12 file with exactly the arm's own Responses patches
on top (SERIES_RESPONSES_PATCHES; arc3: h42): reversing them must give the v12 file byte for byte and re-applying
them the tree's file, and no other patch of the series outside v12's runtime_patches may touch that file.

    python work/qsa_hisparse/probes/pack_kaggle_tree.py --pristine <v0.5.20 checkout> --out-root <staging dir> \\
        [--arm arc3] [--carry <earlier staging dir>]
    kaggle datasets create -p <staging dir>/<slug>          # first version (private)
    kaggle datasets version -p <staging dir>/<slug> -m ...   # later versions

Prints the notebook config's `sglang_tree` block. Refuses to stage when the tree is not TREE_DIGEST's (TREE_DIGEST.<arm>),
when its 0018 (serving_responses.py) is not the file the v12 submission serves (for a series arm: that file plus
the arm's Responses patches), or when anything staged looks like a credential.
"""

from __future__ import annotations

import argparse
import io
import json
import re
import shutil
import subprocess
import sys
import tarfile
import tempfile
from pathlib import Path

HERE = Path(__file__).resolve().parent
sys.path.insert(0, str(HERE.parent))
import g4_runtime  # noqa: E402
from arcforge import sglang_series  # noqa: E402  (g4_runtime put src/ on sys.path)

REPO = g4_runtime.REPO
MANIFEST = g4_runtime.PATCHES / "experimental-hisparse" / "SOURCE_SHA256"
V12 = REPO / "work/arc_code/kaggle/notebook-reap320-0520-v12-submit.json"
RESPONSES = "sglang/srt/entrypoints/openai/serving_responses.py"
#: series arm -> the patches (relative to patches/sglang-0.5.20, in series order) it applies to serving_responses.py
#: on top of the v12 file
SERIES_RESPONSES_PATCHES = {"arc3": ("experimental-hisparse/candidates/h42-responses-single-prompt-encode.patch",)}
OWNER = "threerabbits"
VERSION_PY = ('# generated by pack_kaggle_tree.py (as package_runtime_sm120_0520.sh)\n'
              'from __future__ import annotations\n__version__ = "0.5.20"\n'
              "__version_tuple__ = ('0', '5', '20')\n")
#: names and contents that must never be in a dataset (credentials, signed URLs, keys)
BAD_NAMES = re.compile(r"(^|/)(kaggle\.json|\.env|upstream_key|tokens|[^/]*links[^/]*\.json|[^/]*-manifest\.json)$")
BAD_TEXT = re.compile(rb'"key"\s*:\s*"[0-9a-f]{32}"|KGAT_[A-Za-z0-9]{16,}|X-Goog-Signature=|ghp_[A-Za-z0-9]{36}'
                      rb"|-----BEGIN [A-Z ]*PRIVATE KEY-----|sk-ant-[A-Za-z0-9_-]{20,}|AKIA[0-9A-Z]{16}")


def sha256(path: Path) -> str:
    return g4_runtime.sha256_file(path)


def touches(patch: Path, rel: str) -> bool:
    """Whether a git-format patch has a diff for repo path ``rel``."""
    return f"diff --git a/{rel} b/{rel}\n" in patch.read_text()


def series_responses_patches(arm: str, series: list[Path], v12_patches: list[str]) -> list[Path]:
    """The arm's own Responses patches (SERIES_RESPONSES_PATCHES), checked against its series: every series patch
    that touches serving_responses.py is either one v12 was built with (its runtime_patches, e.g. 0017/0018) or one
    of these, and these are in the series, in this order."""
    declared = [g4_runtime.PATCHES / rel for rel in SERIES_RESPONSES_PATCHES[arm]]
    touching = [p for p in series if touches(p, f"python/{RESPONSES}") and p.name not in v12_patches]
    if touching != declared:
        raise SystemExit(f"{arm}: the series patches touching python/{RESPONSES} beyond v12's runtime_patches are "
                         f"{[p.name for p in touching]}, SERIES_RESPONSES_PATCHES says {[p.name for p in declared]}")
    return declared


def responses_on_v12(tree_file: Path, patches: list[Path], v12_sha: str, tmp: Path) -> dict:
    """tree_file must be the v12 serving_responses.py (sha256 v12_sha) with ``patches`` applied: reverse them (last
    first, only that file's hunks, no fuzz) and the result must be v12's file byte for byte; apply them again and
    the result must be tree_file byte for byte."""
    rel = f"python/{RESPONSES}"
    work = tmp / "responses-check"
    shutil.rmtree(work, ignore_errors=True)
    (work / rel).parent.mkdir(parents=True)
    shutil.copyfile(tree_file, work / rel)

    def apply(patch: Path, *flags: str) -> None:
        done = subprocess.run(["git", "apply", *flags, f"--include={rel}", str(patch)], cwd=work,
                              capture_output=True, text=True)
        if done.returncode:
            raise SystemExit(f"{patch.name} {'reversed ' if flags else ''}does not apply to the tree's {rel}: "
                             f"{done.stderr.strip()}")

    for patch in reversed(patches):
        apply(patch, "-R")
    base = sha256(work / rel)
    if base != v12_sha:
        raise SystemExit(f"the tree's {rel} without {[p.name for p in patches]} is {base}; the v12 submission "
                         f"serves {v12_sha}")
    for patch in patches:
        apply(patch)
    tree = sha256(tree_file)
    if sha256(work / rel) != tree:
        raise SystemExit(f"v12's {rel} + {[p.name for p in patches]} is {sha256(work / rel)}, the tree has {tree}")
    return {"serving_responses_sha256": tree, "serving_responses_v12_sha256": base,
            "serving_responses_patches": [p.relative_to(g4_runtime.PATCHES).as_posix() for p in patches]}


def pack(python_dir: Path, out: Path) -> None:
    """python/sglang/** as a deterministic tar (sorted, mtime/uid zeroed, modes normalised), then zstd."""
    def norm(info: tarfile.TarInfo) -> tarfile.TarInfo:
        info.mtime, info.uid, info.gid, info.uname, info.gname = 0, 0, 0, "", ""
        if not info.issym():
            info.mode = 0o755 if info.isdir() or info.mode & 0o100 else 0o644
        return info

    raw = io.BytesIO()
    with tarfile.open(fileobj=raw, mode="w", format=tarfile.PAX_FORMAT) as tar:
        for path in [python_dir / "sglang", *sorted((python_dir / "sglang").rglob("*"))]:
            if "__pycache__" in path.parts or path.suffix == ".pyc":
                continue
            tar.add(path, arcname=path.relative_to(python_dir.parent).as_posix(), recursive=False, filter=norm)
    plain = out.with_suffix("")  # .tar
    plain.write_bytes(raw.getvalue())
    subprocess.run(["zstd", "-q", "-10", "--rm", "-f", "-o", str(out), str(plain)], check=True)


def unpack_and_digest(archive: Path, tmp: Path) -> dict:
    """What the notebook will do: zstd -d, refuse any member outside python/sglang/, extract, digest."""
    plain = tmp / "check.tar"
    subprocess.run(["zstd", "-q", "-d", "-f", "-o", str(plain), str(archive)], check=True)
    dest = tmp / "check"
    with tarfile.open(plain) as tar:
        bad = [m.name for m in tar.getmembers() if not (m.name == "python/sglang" or m.name.startswith("python/sglang/"))]
        if bad:
            raise SystemExit(f"members outside python/sglang/: {bad[:5]}")
        tar.extractall(dest, filter="tar")
    pkg = dest / "python" / "sglang"
    if (pkg / "_version.py").read_text() != VERSION_PY:
        raise SystemExit("the packed _version.py is not the one written")
    entries = g4_runtime.package_manifest(pkg)
    return {"digest": g4_runtime.manifest_digest(entries), "files": len(entries), "root": dest}


def scan(paths: list[Path]) -> None:
    hits = []
    for root in paths:
        for path in [root] if root.is_file() else sorted(p for p in root.rglob("*") if p.is_file() and not p.is_symlink()):
            if BAD_NAMES.search(path.as_posix()):
                hits.append(f"name {path}")
            elif path.suffix not in (".zst", ".tar") and BAD_TEXT.search(path.read_bytes()):
                hits.append(f"content {path}")
    if hits:
        raise SystemExit("credential-looking files, not staging:\n  " + "\n  ".join(hits[:20]))


def carry(src: Path, stage: Path) -> list[str]:
    """Copy every tree an earlier staging dir holds (TREE*.json + the archive and manifest it names) into stage,
    each file re-verified against its record. A name already staged is an error, never an overwrite."""
    records = sorted(src.glob("TREE*.json"))
    if not records:
        raise SystemExit(f"{src} holds no TREE*.json: not a staging dir of this dataset")
    copied = []
    for rec_path in records:
        rec = json.loads(rec_path.read_text())
        for name, pinned in ((rec["archive"], rec["archive_sha256"]), (rec["manifest"], rec["manifest_sha256"]),
                             (rec_path.name, None)):
            if (stage / name).exists():
                raise SystemExit(f"{name} from {src} is already staged: two trees would share a file name")
            if pinned is not None and sha256(src / name) != pinned:
                raise SystemExit(f"{src / name} is not the file its record pins ({pinned[:12]})")
            shutil.copyfile(src / name, stage / name)
            copied.append(name)
    return copied


def main() -> int:
    p = argparse.ArgumentParser(description=__doc__.splitlines()[0])
    p.add_argument("--pristine", type=Path, required=True, help="a v0.5.20 checkout at patches/sglang-0.5.20/BASE")
    p.add_argument("--out-root", type=Path, required=True)
    p.add_argument("--slug", default="qsa-hisparse-sglang-tree")
    p.add_argument("--arm", choices=("hisparse",) + tuple(sglang_series.SERIES), default="hisparse",
                   help="hisparse (TREE_DIGEST's row, the default) or a series arm (TREE_DIGEST.<arm>)")
    p.add_argument("--carry", type=Path, action="append", default=[],
                   help="an earlier staging dir of this dataset whose trees this version keeps (repeatable)")
    a = p.parse_args()
    series = a.arm in sglang_series.SERIES
    if series:
        try:
            want = sglang_series.read_row(g4_runtime.PATCHES, a.arm)
        except (OSError, ValueError) as error:
            raise SystemExit(str(error)) from error
        if g4_runtime.patches_digest(a.arm) != want["patches"]:
            raise SystemExit(f"TREE_DIGEST.{a.arm} was written for other patches: regenerate it first "
                             f"(g4_runtime.py series-write --arm {a.arm})")
        manifest_src = sglang_series.manifest_path(g4_runtime.PATCHES, a.arm)
    else:
        want = g4_runtime.read_tree_digest()["hisparse"]
        if g4_runtime.patches_digest("hisparse") != want["patches"]:
            raise SystemExit("TREE_DIGEST was written for other hisparse patches: regenerate it first (g4_runtime.py tree-write)")
        manifest_src = MANIFEST
    v12 = json.loads(V12.read_text())
    overlay = [e for e in v12["runtime_overlay"] if e["dest"] == f"python/{RESPONSES}"]
    if len(overlay) != 1:
        raise SystemExit(f"{V12.name} has no single overlay for python/{RESPONSES}")
    if series:
        responses_patches = series_responses_patches(a.arm, g4_runtime.patch_set(a.arm), v12["runtime_patches"])
    stage = a.out_root / a.slug
    if stage.exists():
        meta = stage / "dataset-metadata.json"
        if not meta.is_file() or json.loads(meta.read_text()).get("id") != f"{OWNER}/{a.slug}":
            raise SystemExit(f"{stage} exists and is not this dataset's staging dir; not deleting it")
        shutil.rmtree(stage)
    stage.mkdir(parents=True)
    with tempfile.TemporaryDirectory(dir=a.out_root) as tmpdir:
        tmp = Path(tmpdir)
        pkg = g4_runtime.build_tree(a.pristine, a.arm, tmp / "tree")
        (pkg / "_version.py").write_text(VERSION_PY)
        built = g4_runtime.tree_check(pkg, a.arm, None)
        if series:
            responses = responses_on_v12(pkg.parent / RESPONSES, responses_patches, overlay[0]["result_sha256"], tmp)
        else:
            responses = {"serving_responses_sha256": sha256(pkg.parent / RESPONSES)}
            if responses["serving_responses_sha256"] != overlay[0]["result_sha256"]:
                raise SystemExit(f"the tree's {RESPONSES} is {responses['serving_responses_sha256']}; the v12 "
                                 f"submission serves {overlay[0]['result_sha256']} (its runtime_overlay): 0018 differs")
        archive = stage / f"sglang-{a.arm}-{built['digest'][:12]}.tar.zst"
        pack(pkg.parent, archive)
        check = unpack_and_digest(archive, tmp)
        if (check["digest"], check["files"]) != (want["digest"], want["files"]):
            raise SystemExit(f"the packed tree is {check['digest'][:12]} ({check['files']} files), "
                             f"TREE_DIGEST{'.' + a.arm if series else ''} says {want['digest'][:12]} ({want['files']})")
        scan([check["root"]])
    tag = want["digest"][:12]
    manifest = stage / f"SOURCE_SHA256-{tag}"
    shutil.copyfile(manifest_src, manifest)
    record = {**({"arm": a.arm} if series else {}),
              "tree_digest": want["digest"], "tree_files": want["files"], "patches_digest": want["patches"],
              "manifest": manifest.name, "manifest_sha256": sha256(manifest),
              "archive": archive.name, "archive_sha256": sha256(archive), "archive_bytes": archive.stat().st_size,
              **responses,
              "arc_forge_commit": subprocess.run(["git", "-C", str(REPO), "rev-parse", "HEAD"], check=True,
                                                 capture_output=True, text=True).stdout.strip(),
              "base_ref": re.search(r"^REF=([0-9a-f]{40})", (g4_runtime.PATCHES / "BASE").read_text(), re.M).group(1)}
    (stage / f"TREE-{tag}.json").write_text(json.dumps(record, indent=1) + "\n")
    carried = [carry(src, stage) for src in a.carry]
    (stage / "dataset-metadata.json").write_text(json.dumps(
        {"title": "qsa hisparse sglang tree", "id": f"{OWNER}/{a.slug}", "licenses": [{"name": "other"}]},
        indent=1) + "\n")
    scan([stage])
    # tree_commit must end up in main's history (build_notebook checks): packed on a branch, record the main
    # commit that carries the same patches/ tree once it is merged
    block = {"dataset": f"{OWNER}/{a.slug}", **({"arm": a.arm} if series else {}), **{k: record[k] for k in (
        "archive", "archive_sha256", "tree_digest", "tree_files", "manifest", "manifest_sha256")},
        "tree_commit": record["arc_forge_commit"]}
    print(f"staged {stage}: {archive.name} {record['archive_bytes'] / 2**20:.1f} MiB, "
          f"tree {want['digest'][:12]} ({want['files']} files), manifest {record['manifest_sha256'][:12]}; "
          f"carried {sum(carried, [])}")
    print(json.dumps({"sglang_tree": block}, indent=1))
    return 0


if __name__ == "__main__":
    raise SystemExit(main())
